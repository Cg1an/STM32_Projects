#include "CH351.h"
//BD时钟接线盒设备
//  GPIO1 X0-X7   接KEY
//  GPIO2 X8-X15  接KEY
//  GPIO3 X16-X20  接LED
//  GPIO4 X24-X28  接KEY 5个
void CH351_LCD_4LED_21KEYinit(void)
{
	 CH351_RST_RESET;  
	 CH351_RST_SET;
	
	 CH351_WRITE_SET(CH351_MODE_GPIO1,0X00);//1为输出模式
	 CH351_WRITE_SET(CH351_MODE_GPIO2,0X00);//1为输出模式
	 CH351_WRITE_SET(CH351_MODE_GPIO3,0XFF);//0为输入模式
	 CH351_WRITE_SET(CH351_MODE_GPIO4,0X00);//1为输出模式
	
	 CH351_WRITE_SET(CH351_GPIO1,0XFF);//0为下拉
	 CH351_WRITE_SET(CH351_GPIO2,0XFF);//0为下拉
	 CH351_WRITE_SET(CH351_GPIO3,0X00);//1为上拉
	 CH351_WRITE_SET(CH351_GPIO4,0XFF);//0为下拉
}

uint32_t CH351_READ_21KEY(void)
{
	  uint32_t key=0;
    key+=CH351_READ_SET(CH351_GPIO1);
  	key=key<<8;
	  key+=CH351_READ_SET(CH351_GPIO2);
  	key=key<<8;
	  key+=CH351_READ_SET(CH351_GPIO4);
	  return key;
}
void CH351_WRITE_4LED(uint8_t LED_SET)
{  
 	  CH351_WRITE_SET(CH351_GPIO3,LED_SET);//0为下拉
}

