#include "CH351.h"
//网络通信控制设备中 
//  GPIO1 X0-X7   接LED
//  GPIO2 X8-X15  接LED
//  GPIO3 X16-X123 接LED
//  GPIO4 X24-X25  接KEY 2个
void CH351_24LED_2KEY_init(void)
{
	 CH351_RST_RESET;  
	 CH351_RST_SET;
	
	 CH351_WRITE_SET(CH351_MODE_GPIO1,0XFF);//1为输出模式
	 CH351_WRITE_SET(CH351_MODE_GPIO2,0XFF);//1为输出模式
	 CH351_WRITE_SET(CH351_MODE_GPIO3,0XFF);//0为输入模式
	 CH351_WRITE_SET(CH351_MODE_GPIO4,0X00);//1为输出模式
	
	 CH351_WRITE_SET(CH351_GPIO1,0X00);//0为下拉
	 CH351_WRITE_SET(CH351_GPIO2,0X00);//0为下拉
	 CH351_WRITE_SET(CH351_GPIO3,0X00);//1为上拉
	 CH351_WRITE_SET(CH351_GPIO4,0XFF);//0为下拉
}

uint8_t CH351_READ_24_2KEY(void)
{
	  uint8_t key;
    key=CH351_READ_SET(CH351_GPIO4);
	  return key;
}
void CH351_WRITE_24LED(uint32_t LED_SET)
{
   CH351_WRITE_SET(CH351_GPIO1,(uint8_t) LED_SET);//0为下拉
   CH351_WRITE_SET(CH351_GPIO2,(uint8_t)(LED_SET>>8));//0为下拉
 	 CH351_WRITE_SET(CH351_GPIO3,(uint8_t)(LED_SET>>16));//0为下拉
}

